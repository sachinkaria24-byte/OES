def check_claim(x, bit, extra):
    r = x % N
    if bit is None:
        ok = r == 0
    else:
        ok = r != 0 and ledger.contains_tick(r) == bit == (x % 5 != 0)
    for e in extra:
        kind = e[0]
        if kind == "order":
            ok &= spine.order(r) == e[1]
        elif kind == "same":
            ok &= gcd(r, N) == gcd(e[1] % N, N)
        elif kind == "notsame":
            ok &= gcd(r, N) != gcd(e[1] % N, N)
        elif kind == "gen":
            ok &= gcd(r, N) == 1
        elif kind == "notgen":
            ok &= gcd(r, N) != 1
        elif kind == "land":
            ok &= first_landing(r) == (e[1], e[2])
        elif kind == "noland":
            ok &= first_landing(r) is None
        elif kind == "steps":
            ok &= ledger.steps_to_tick(r) == e[1]
        elif kind == "res":
            ok &= r == e[1]
        elif kind == "mod5":
            ok &= x % 5 == e[1]
        elif kind == "notlevel":
            ok &= r not in LEVELS
        elif kind == "in":
            ok &= r % gcd(e[1], N) == 0
        elif kind == "notin":
            ok &= r % gcd(e[1], N) != 0
        else:
            raise ValueError(kind)
    return bool(ok)


